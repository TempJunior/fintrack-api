-- Schema inicial do Fintrack (fintrack-modelo-dados.md §5).
-- Escrito para rodar igual no H2 (modo PostgreSQL) e no PostgreSQL 15+.
-- Regra do Flyway: depois de aplicada, esta migration NUNCA é alterada. Mudança = nova migration (V2, V3...).

CREATE TABLE contas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instituicao     VARCHAR(20)  NOT NULL,
    tipo            VARCHAR(20)  NOT NULL,
    apelido         VARCHAR(60)  NOT NULL,
    moeda           VARCHAR(3)   NOT NULL DEFAULT 'BRL',
    numero_externo  VARCHAR(40),
    ativa           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE categorias (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(60) NOT NULL,
    categoria_pai_id  BIGINT REFERENCES categorias (id),
    -- NULLS NOT DISTINCT: duas categorias raiz (pai nulo) com o mesmo nome também colidem.
    CONSTRAINT uk_categorias_pai_nome UNIQUE NULLS NOT DISTINCT (categoria_pai_id, nome)
);

CREATE TABLE regras_categorizacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id  BIGINT       NOT NULL REFERENCES categorias (id),
    operador      VARCHAR(20)  NOT NULL,
    padrao        VARCHAR(255) NOT NULL,
    prioridade    INTEGER      NOT NULL
);

CREATE TABLE transacoes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- dado bruto (imutável — RF11, RNF06)
    conta_id               BIGINT        NOT NULL REFERENCES contas (id),
    fit_id                 VARCHAR(255),
    dedup_key              VARCHAR(255)  NOT NULL,
    data_postada           DATE          NOT NULL,
    valor                  NUMERIC(15,2) NOT NULL,
    descricao_original     VARCHAR(255)  NOT NULL,
    -- enriquecimento
    categoria_id           BIGINT REFERENCES categorias (id),
    origem_categoria       VARCHAR(10),
    nota                   VARCHAR(500),
    transferencia_interna  BOOLEAN       NOT NULL DEFAULT FALSE,
    -- Dedup (RF07, RNF04, ADR-005)
    CONSTRAINT uk_transacoes_conta_dedup UNIQUE (conta_id, dedup_key),
    -- Categoria e origem andam juntas (D-11)
    CONSTRAINT ck_transacoes_origem_categoria CHECK ((origem_categoria IS NULL) = (categoria_id IS NULL))
);

CREATE INDEX idx_transacoes_conta_data ON transacoes (conta_id, data_postada DESC);
CREATE INDEX idx_transacoes_categoria ON transacoes (categoria_id);

CREATE TABLE transacao_tags (
    transacao_id  BIGINT      NOT NULL REFERENCES transacoes (id),
    tag           VARCHAR(40) NOT NULL,
    PRIMARY KEY (transacao_id, tag)
);

CREATE TABLE importacoes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id         BIGINT                   NOT NULL REFERENCES contas (id),
    nome_arquivo     VARCHAR(255)             NOT NULL,
    formato          VARCHAR(10),
    data_hora        TIMESTAMP WITH TIME ZONE NOT NULL,
    total_lido       INTEGER                  NOT NULL,
    novas            INTEGER                  NOT NULL,
    duplicadas       INTEGER                  NOT NULL,
    erros            INTEGER                  NOT NULL,
    resultado        VARCHAR(10)              NOT NULL,
    -- LEDGERBAL do arquivo (D-10)
    saldo_declarado  NUMERIC(15,2),
    data_saldo       DATE
);

CREATE INDEX idx_importacoes_conta_data ON importacoes (conta_id, data_hora DESC);
